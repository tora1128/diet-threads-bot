#!/usr/bin/env python3
"""恋愛お姉さん系の短文投稿を生成するツール"""

import datetime
import random

_WEEKDAYS = ["月", "火", "水", "木", "金", "土", "日"]

_MORNING_MESSAGES = [
    "おはよう。朝からあの人のことを考えてしまう日もあるよね。\n\nでも今日は、返事を待つより先に自分の気持ちを整えてあげて。\n恋は、あなたが苦しくなるためのものじゃないよ。",
    "おはよう。連絡したい気持ちがあるなら、まず深呼吸してみて。\n\n送るかどうかより、送った後の自分を守れるかが大事。\n今日は焦らず、やさしい選択をしてね。",
    "おはよう。好きな人の一言で、気持ちが揺れることってあるよね。\n\nでも、相手の反応だけで今日の自分を決めなくて大丈夫。\nあなたの一日もちゃんと大切にして。",
    "おはよう。復縁したい気持ちは、無理に消さなくていいよ。\n\nただ、その気持ちで自分を責めすぎないでね。\n戻る縁なら、あなたが壊れなくてもちゃんと近づいてくる。",
    "おはよう。今日は、恋を頑張る前に自分を整える日でもいい。\n\n無理に明るくしなくて大丈夫。\nあなたが少し楽でいられる選択をしてね。",
    "おはよう。待つ恋は、見えないところで心を使うよね。\n\n今日は相手のことを考える時間を少しだけ減らして、自分に戻る時間を作ってみて。",
]

_NOON_MESSAGES = [
    "昼になると、朝より少し冷静に考えられることもあるよね。\n\n連絡するなら、寂しさを埋めるためじゃなくて、ちゃんと伝えたいことがある時にしてみて。",
    "好きな人の反応が遅いと、不安になるよね。\n\nでも、返事の速さだけで愛情を測らなくて大丈夫。\n今日は自分の予定も少し大切にして。",
    "復縁したい時ほど、相手の気持ちばかり見にいってしまうよね。\n\nでも本当は、自分がもう一度その関係で幸せになれるかも大事だよ。",
    "既読スルーって、心が止まるみたいに感じることあるよね。\n\nでも、そこで自分の価値まで下げなくていい。\n今日は少しだけスマホから離れてみて。",
    "あの人に選ばれるかより、あなたが安心していられる恋かどうか。\n\nそこを見失わないでね。\n好きな気持ちは大事。でも自分を守ることも同じくらい大事。",
    "気持ちを伝えるのは勇気がいるよね。\n\nでも、伝える前に相手の反応を全部想像して疲れなくていい。\n今日はできることを一つだけで大丈夫。",
]


def generate_love_message(date: datetime.date, message_type: str) -> str:
    """朝・昼用の恋愛短文投稿を返す"""
    if message_type == "morning_message":
        pool = _MORNING_MESSAGES
        label = "朝の恋愛ひとこと"
    elif message_type == "noon_message":
        pool = _NOON_MESSAGES
        label = "昼の恋愛ひとこと"
    else:
        raise ValueError(f"未対応の投稿タイプ: {message_type}")

    date_str = f"{date.month}/{date.day}({_WEEKDAYS[date.weekday()]})"
    message = random.Random(date.toordinal() + len(message_type) * 1000).choice(pool)

    return "\n".join(
        [
            f"🌙 {date_str} {label}",
            message,
            "",
            "今のあなたに届いたら「🌙」で教えてね。",
        ]
    )
