def _make_ranking(date: datetime.date) -> list[str]:
    rng = random.Random(date.toordinal())
    signs = SIGNS[:]
    rng.shuffle(signs)
    return signs


def _pick(pool: list[tuple], seed: int) -> tuple[str, str]:
    return random.Random(seed).choice(pool)


def generate_horoscope_posts(date: datetime.date) -> list[str]:
    """3投稿分のテキストリストを返す（API不要）"""
    date_str = f"{date.month}/{date.day}({_WEEKDAYS[date.weekday()]})"
    ranking = _make_ranking(date)
    rng = random.Random(date.toordinal() + 1)
    high_pool = rng.sample(_HIGH, 3)
    mid_pool  = rng.sample(_MID,  3)
    low_pool  = rng.sample(_LOW,  6)

    # ── 投稿1: 1〜3位 ──
    lines = ["📊 明日の星座ランキング", date_str]
    medals = ["🥇 1位", "🥈 2位", "🥉 3位"]
    for i, medal in enumerate(medals):
        headline, body = high_pool[i]
        lines += ["", f"{medal}：{ranking[i]}", headline, body]
    lines += ["", "当てはまる方は星座で教えてね。✨\n\n明日も自分らしく、一歩一歩丁寧に過ごしていきましょう。\n\nどんな日も、あなたの味方でいます✨もっと占って欲しい方はプロフィールへ🔮"]
    post1 = "\n".join(lines)

    # ── 投稿2: 4〜6位 ──
    lines = ["✨ 続いて4〜6位の星座", date_str]
    for i in range(3, 6):
        headline, body = mid_pool[i - 3]
        lines += ["", f"{i + 1}位：{ranking[i]}", headline, body]
    post2 = "\n".join(lines)

    # ── 投稿3: 7〜12位 ──
    lines = ["⚠️ 今日は慎重に…7〜12位", date_str]
    for i in range(6, 12):
        headline, body = low_pool[i - 6]
        lines += ["", f"{i + 1}位：{ranking[i]}", headline, body]
    post3 = "\n".join(lines)

    return [post1, post2, post3]


