def _make_ranking(date: datetime.date, cat_idx: int = 0) -> list[str]:
    rng = random.Random(date.toordinal() + cat_idx * 31337)
    signs = SIGNS[:]
    rng.shuffle(signs)
    return signs


_LUCKY_EMOJIS = [
    "⛩️", "🌙", "🍀", "⭐", "🌸",
    "💫", "🦋", "🌈", "🌺", "🔮",
    "🌟", "💎", "🕊️", "🌻", "🍁",
]


def _shorten_body(body: str, max_len: int = 22) -> str:
    """本文を自然な区切りでmax_len文字以内に短縮する"""
    if len(body) <= max_len:
        return body
    # 最初の。で1文目だけ取れる場合はそれを使う
    first = body.split('。')[0]
    if first and len(first) + 1 <= max_len:
        return first + '。'
    # 。で区切れない場合は、の位置で切る
    cut = body[:max_len]
    for i in range(len(cut) - 1, -1, -1):
        if cut[i] in '、。':
            return cut[:i + 1]
    return cut


def _pick(pool: list, rng: random.Random):
    return rng.choice(pool)


def generate_horoscope_posts(date: datetime.date, category: str = "総合運", rank_date: datetime.date = None) -> list[str]:
    """3投稿分のテキストリストを返す（API不要）"""
    if category not in _CONTENT:
        raise ValueError(f"未対応のカテゴリ: {category}")

    content = _CONTENT[category]
    cat_idx = CATEGORIES.index(category)

    # date=表示日付、rank_date=ランキング生成基準日（省略時はdateと同じ）
    rank_date = rank_date or date

    date_str = f"{date.month}/{date.day}({_WEEKDAYS[date.weekday()]})"
    ranking = _make_ranking(rank_date, cat_idx)

    seed = rank_date.toordinal() + cat_idx * 1000
    rng = random.Random(seed + 1)
    high_pool = rng.sample(content["high"], 3)
    mid_pool  = rng.sample(content["mid"],  3)
    low_pool  = rng.sample(content["low"],  6)

    header1      = random.Random(seed + 10).choice(content["headers1"])
    header2      = random.Random(seed + 11).choice(content["headers2"])
    closing      = random.Random(seed + 13).choice(content["closings"])
    lucky_emoji  = random.Random(seed + 20).choice(_LUCKY_EMOJIS)

    # ── 投稿1: 1〜3位 ──
    lines = [header1, date_str]
    medals = ["🥇 1位", "🥈 2位", "🥉 3位"]
    for i, medal in enumerate(medals):
        headline, body = high_pool[i]
        sign = ranking[i]
        lines += ["", f"{medal}：{_SIGN_EMOJI[sign]}{sign}", headline, body]
    if category in ("恋愛運", "総合運"):
        lines += ["", closing, "", f"本日ラッキーな方は「{lucky_emoji}」で押して教えてね！", "", "LINEを始めてから見えてきたあなたの運気の流れを、無料の鑑定書にまとめています。気になる方はプロフィールのLINEからどうぞ🌙"]
    else:
        lines += ["", closing, "", f"本日ラッキーな方は「{lucky_emoji}」で押して教えてね！"]
    post1 = "\n".join(lines)

    # ── 投稿2: 4〜12位 ──
    lines = [header2, date_str]
    for i in range(3, 6):
        headline, body = mid_pool[i - 3]
        sign = ranking[i]
        lines += ["", f"{i + 1}位：{_SIGN_EMOJI[sign]}{sign}", headline, body]
    for i in range(6, 12):
        headline, body = low_pool[i - 6]
        sign = ranking[i]
        short_body = _shorten_body(body)
        lines += ["", f"{i + 1}位：{_SIGN_EMOJI[sign]}{sign}", headline, short_body]
    post2 = "\n".join(lines)

    return [post1, post2]


